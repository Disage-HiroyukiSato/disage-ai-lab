import logging

from app.config import settings

logger = logging.getLogger(__name__)


class PromptBuilder:

    #
    # ------------------------------------------------------
    # 回答形式別の出力指示
    # ------------------------------------------------------
    #
    # query_rewrite_service.analyze()が判定したresponse_formatに
    # 応じて、LLMへの出力指示を切り替える。
    #
    # 全形式共通の原則：
    #   資料にない表現形式（図・表・比較・手順等）であっても、
    #   資料から得られた知識の範囲内であれば、その知識を
    #   別の表現形式に変換して回答してよい。
    #   ただし、変換の過程で資料にない新しい事実を
    #   追加してはならない。
    #

    FORMAT_INSTRUCTIONS = {

        "EXPLAIN": """
・資料の内容を分かりやすい説明文としてまとめてください。
""",

        "CODE": """
・資料中のコード例を、可能な限りそのまま、または資料の内容に
  忠実な形で提示してください。
・資料にコード例が無い場合、資料の説明内容からコードを
  新規に作成しても構いませんが、資料に書かれていない
  仕様・API・メソッド名を創作しないでください。
""",

        "COMPARE": """
・複数の概念を比較する表または箇条書きの形式で回答してください。
・比較の観点（例：定義、用途、違い）を明確にしてください。
・資料に記載がない比較観点は追加しないでください。
""",

        "STEP_BY_STEP": """
・資料の内容を手順（ステップ）として、番号付きで順を追って
  説明してください。
・資料に手順として明記されていない場合、資料の内容から
  論理的に導ける順序で構いませんが、資料にない手順を
  新しく作り出さないでください。
""",

        "DIAGRAM": """
・資料の内容を構造化し、Mermaid記法で図として表現してください。
・資料にクラス構成やメソッド呼び出しの説明があれば、それを
  そのまま図に変換してください（資料に「フローチャート」という
  形での記載が無くても、資料の内容を図形式に変換することは
  問題ありません）。
・資料にコード例がある場合は、図とあわせてコードも提示して
  ください。
・「資料に記載がない」という言い訳を繰り返す前に、まず
  資料にある情報からどこまで図示できるかを試みてください。
  一部の情報が資料に無い場合は、図示できる範囲だけを示し、
  補えない部分がある場合のみ最後に一言触れる程度に留めて
  ください。
・ただし、図の中に資料に書かれていないクラス名・メソッド名・
  条件分岐を新しく作り出してはいけません。
・Mermaidコードは ```mermaid ``` のコードブロックで
  囲んでください。
""",

        "QUIZ": """
・資料の内容に基づいたクイズ形式（問題と答え）で
  回答してください。
・問題は資料の内容から直接導けるものにしてください。
・資料にない知識を問う問題を作らないでください。
""",

        "DEBUG": """
・提示されたコードやエラーの内容と、資料の内容を照らし合わせて
  原因を説明してください。
・資料から読み取れる原因・対処法のみを回答し、資料にない
  一般的なデバッグ手法を断定的に述べないでください。
・資料だけでは原因を特定できない場合は、その旨を
  明記してください。
""",

        "SUMMARY": """
・資料の内容を簡潔に要約してください。
・要約に際して、資料にない情報を補わないでください。
""",

        "EXAMPLE": """
・資料の内容に基づいた具体例を挙げて回答してください。
・資料に具体例が無い場合、資料の説明内容から矛盾しない
  具体例を作成しても構いませんが、資料にない仕様や
  事実を新たに作り出さないでください。
"""

    }

    def build(

        self,

        question: str,

        contexts: list[str],

        conversation_turns: list[dict] | None = None,

        is_off_topic: bool = False,

        response_format: str = "EXPLAIN"

    ) -> str:

        logger.debug(

            "Prompt created"

        )

        prompt = self._build_internal(

            question,

            contexts,

            conversation_turns,

            is_off_topic,

            response_format

        )

        if settings.log_prompt:

            logger.debug(
                "Prompt\n%s",
                prompt
            )

        return prompt

    def _format_history(

        self,

        conversation_turns: list[dict] | None

    ) -> str:

        if not conversation_turns:

            return ""

        lines = []

        for turn in conversation_turns:

            role = turn.get(

                "role",

                ""

            )

            content = turn.get(

                "content",

                ""

            )

            speaker = (

                "受講生"

                if role == "user"

                else "アシスタント"

            )

            lines.append(

                f"{speaker}: {content}"

            )

        history_text = "\n".join(

            lines

        )

        return f"""
# これまでの会話

{history_text}
"""

    def _build_internal(

        self,

        question: str,

        contexts: list[str],

        conversation_turns: list[dict] | None,

        is_off_topic: bool,

        response_format: str

    ) -> str:

        context = "\n\n".join(contexts)

        history_section = self._format_history(

            conversation_turns

        )

        off_topic_instruction = ""

        if is_off_topic:

            off_topic_instruction = """
・この質問はJava研修教材の範囲外である可能性があります。
・回答の冒頭で「この内容はJava研修教材の範囲外です。」と一言明示してから、
  分かる範囲で回答してください。
・教材に基づかない一般知識で補う場合は、資料からの回答ではないことが
  分かるようにしてください。
"""

        format_instruction = self.FORMAT_INSTRUCTIONS.get(

            response_format,

            self.FORMAT_INSTRUCTIONS["EXPLAIN"]

        )

        return f"""
あなたはJava研修受講生向けのAI学習アシスタントです。

# 方針

・資料の内容だけを根拠にして回答してください。
・資料に「質問への直接の回答」が含まれている場合のみ回答してください。
・資料中に質問と同じ単語が含まれているだけでは、回答の根拠として不十分です。
  単語の一致ではなく、質問の意図そのものに資料が答えているかで判断してください。
・資料がコード例（サンプルコード、コードブロック、変数名、出力例など）を
  含む場合、それはJavaの説明のための例示であり、実際のデータ・実行結果・
  現在の状態を表すものではありません。コード中の値や文字列を事実として
  扱わないでください。
・資料にない表現形式（図、表、比較、手順、クイズなど）で回答を求められた
  場合でも、資料から得られる知識の範囲内であれば、その知識を別の表現形式に
  変換して回答してください。表現形式を変えることと、内容を推測で
  補うことは別です。変換の過程で資料に書かれていない新しい事実・仕様・
  固有名詞を追加してはいけません。
・資料の一部にしか情報が無い場合でも、「資料からは確認できません」と
  全面的に回答を拒否するのではなく、資料にある範囲でできる限り
  具体的に答えてください。回答を拒否してよいのは、資料に質問へ
  関連する情報が全く含まれていない場合のみです。
  一部の情報が不足している場合は、答えられる部分を先に述べたうえで、
  不足している点を最後に一言添える程度に留めてください。
・これまでの会話の文脈を踏まえて回答してください。

# 回答スタイル

・結論を最初に述べてください。前置きや言い訳から始めないでください。
・「〜する必要があります」「〜してください」のような、受講生に
  作業を丸投げする言い回しを繰り返さないでください。あなたが
  代わりにできることは、この場で実際に行ってください。
・同じ内容を異なる言い回しで何度も説明しないでください。
  一度述べたことを別の文で繰り返さないでください。
・冗長な前置き・言い訳・免責事項を並べず、簡潔に本題から
  答えてください。

# 回答形式の指示

{format_instruction}

# 禁止事項

・資料に記載のない内容を推測・補完しないでください。
・資料中の単語がたまたま質問に含まれているだけで、無関係な内容を
  回答に含めないでください。
・同じ内容や同じ文を繰り返さないでください。
・指示されていない追加の質問、補足、次の話題の提案などを
  自発的に付け足さないでください。回答は求められたことにのみ答えてください。
・資料だけでは全く回答できない場合（質問に関連する情報が資料に
  一切無い場合）のみ、無理に何かを答えようとせず、
  「資料からは確認できません。」とだけ回答してください。
  資料に部分的にでも関連情報がある場合は、この定型文を
  使わず、分かる範囲を回答してください。
{off_topic_instruction}
# 出力形式

・日本語で回答してください。
・簡潔に、箇条書きを優先して回答してください（DIAGRAM形式の場合を除く）。
・200文字以内を目安にしてください（コード・図・表を除く）。
・資料中に複数の候補がある場合は、全て列挙してください。
{history_section}
# 資料

{context}

# 質問

{question}

# 回答
"""


prompt_builder = PromptBuilder()