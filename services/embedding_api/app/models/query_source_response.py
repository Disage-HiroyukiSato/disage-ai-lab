from pydantic import BaseModel


class QuerySourceResponse(BaseModel):

    # ======================================================
    # Document
    # ======================================================
    #
    # 回答の根拠となった資料の識別子。
    #
    # ======================================================

    document_id: str = ""

    # ======================================================
    # Chunk
    # ======================================================
    #
    # 回答の根拠となったchunk番号。
    #
    # APIレスポンス上は文字列として統一する。
    #
    # ======================================================

    chunk_no: str = ""

    # ======================================================
    # Title
    # ======================================================
    #
    # 根拠資料のタイトル。
    #
    # ======================================================

    title: str = ""

    # ======================================================
    # Page Reference
    # ======================================================
    #
    # 原資料上のページ情報。
    #
    # 例：
    #
    #     p.12
    #     p.12-13
    #
    # page / page_number ではなく、
    # page_reference を正式な項目名とする。
    #
    # ======================================================

    page_reference: str | None = None