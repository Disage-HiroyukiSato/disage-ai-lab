from pydantic import BaseModel


class QueryMetadataResponse(BaseModel):

    # ======================================================
    # Query Analysis
    # ======================================================
    #
    # 質問の正規化・解析・書き換え等に要した時間。
    #
    # 回答本文とは無関係なシステム処理情報。
    #
    # ======================================================

    query_analysis_elapsed_ms: int = 0

    # ======================================================
    # Retrieval
    # ======================================================
    #
    # RAG検索に要した時間。
    #
    # ======================================================

    retrieval_elapsed_ms: int = 0

    # ======================================================
    # Answerability
    # ======================================================
    #
    # Answerability Gateによる
    # FULL / PARTIAL / NONE 判定に要した時間。
    #
    # ======================================================

    answerability_elapsed_ms: int = 0

    # ======================================================
    # LLM
    # ======================================================
    #
    # LLMによる回答生成に要した時間。
    #
    # ======================================================

    llm_elapsed_ms: int = 0

    # ======================================================
    # Total
    # ======================================================
    #
    # 質問受付から最終レスポンス生成までの
    # 全体処理時間。
    #
    # ======================================================

    total_elapsed_ms: int = 0

    # ======================================================
    # Cache
    # ======================================================
    #
    # キャッシュが利用されたか。
    #
    # True:
    #     キャッシュヒット
    #
    # False:
    #     キャッシュ未使用 / キャッシュミス
    #
    # ======================================================

    cache_hit: bool = False

    # ======================================================
    # Retrieval Fallback
    # ======================================================
    #
    # 通常の検索結果が弱かったため、
    # フォールバック検索を実施したか。
    #
    # ======================================================

    fallback_used: bool = False

    # ======================================================
    # Retrieved Count
    # ======================================================
    #
    # RAG検索によって取得された候補数。
    #
    # ======================================================

    retrieved_count: int = 0

    # ======================================================
    # Answerability Gate Candidate Count
    # ======================================================
    #
    # Answerability Gateの判定対象となった候補数。
    #
    # ======================================================

    gate_candidate_count: int = 0

    # ======================================================
    # Final Context Count
    # ======================================================
    #
    # 重複除去等を行った後、
    # 最終的にLLMへ渡したコンテキスト数。
    #
    # ======================================================

    final_context_count: int = 0