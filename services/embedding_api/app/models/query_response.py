from pydantic import BaseModel, Field

from app.models.query_document_response import (
    QueryDocumentResponse
)

from app.models.query_metadata_response import (
    QueryMetadataResponse
)

from app.models.query_source_response import (
    QuerySourceResponse
)


class QueryResponse(BaseModel):

    # ======================================================
    # 回答本文
    # ======================================================
    #
    # LLMが生成した最終回答。
    #
    # 回答内容そのものを格納する。
    #
    # ======================================================

    answer: str = ""

    # ======================================================
    # 回答の根拠
    # ======================================================
    #
    # RAGから取得した、回答の根拠・参考資料。
    #
    # 回答本文とは分離して保持する。
    #
    # ======================================================

    sources: list[QuerySourceResponse] = Field(
        default_factory=list
    )

    # ======================================================
    # 参考ページ
    # ======================================================
    #
    # 回答に利用したRAG資料のページ情報。
    #
    # 例：
    #
    #     ["p.12", "p.13"]
    #
    # ページ情報はRAG metadataに存在するものだけを使用し、
    # LLMやAPI側で推測・生成しない。
    #
    # ======================================================

    source_pages: list[str] = Field(
        default_factory=list
    )

    # ======================================================
    # 従来レスポンスとの互換項目
    # ======================================================
    #
    # 既存クライアントとの互換性を維持するための項目。
    #
    # 詳細な処理時間・検索情報はmetadataに集約する。
    #
    # ======================================================

    elapsed_ms: int = 0

    retrieved_count: int = 0

    # ======================================================
    # RAG検索結果
    # ======================================================
    #
    # 実際に最終回答生成に使用した検索結果。
    #
    # sourcesとは目的が異なる。
    #
    # sources:
    #     回答の根拠として参照する資料情報
    #
    # documents:
    #     RAG検索で得られた詳細な検索結果
    #
    # ======================================================

    documents: list[QueryDocumentResponse] = Field(
        default_factory=list
    )

    # ======================================================
    # Answerability
    # ======================================================
    #
    # RAG資料に対して質問へ回答可能かを示す。
    #
    # FULL:
    #     資料に十分な根拠がある。
    #
    # PARTIAL:
    #     関連情報はあるが、質問の一部を資料から
    #     確認できない。
    #
    # NONE:
    #     質問に関連する資料が確認できない。
    #
    # ======================================================

    answerability_status: str | None = None

    # ======================================================
    # Answerability理由
    # ======================================================
    #
    # Answerability Gateが判定した理由。
    #
    # これは回答本文とは別の判定情報。
    #
    # ======================================================

    answerability_reason: str = ""

    # ======================================================
    # システム情報
    # ======================================================
    #
    # 検索時間、LLM処理時間、総処理時間など、
    # 回答本文とは直接関係しない処理情報を格納する。
    #
    # ======================================================

    metadata: QueryMetadataResponse